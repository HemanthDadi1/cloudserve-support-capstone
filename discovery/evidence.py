"""Stage 1 discovery evidence: counts the development tickets into tables for the workbook.

Usage: python -m discovery.evidence [--tickets PATH] [--docs PATH] [--output PATH]

Every table has an evidence ID (E1, E2, ...) so workbook rows and PRD requirements can cite it.
The script reports figures only; interpreting them is done in the workbook.
"""
import argparse
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent


def pct(x):
    return f"{100 * x:.0f}%"


def table(df):
    df = df.reset_index() if df.index.name else df
    cols = [str(c) for c in df.columns]
    rows = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    rows += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(rows)


def outcomes_by(df, col):
    g = df.groupby(col)
    return pd.DataFrame({
        "tickets": g.size(),
        "share": (g.size() / len(df)).map(pct),
        "FCR": g["fcr"].mean().map(pct),
        "escalated": g["escalated"].mean().map(pct),
        "mean CSAT": g["csat"].mean().round(2),
        "repeat contact": g["repeat"].mean().map(pct),
        "median resolution min": g["minutes"].median().astype(int),
    }).sort_values("tickets", ascending=False)


def load(tickets_path):
    df = pd.json_normalize(json.loads(Path(tickets_path).read_text()))
    return df.rename(columns={
        "labels.intent": "intent", "labels.urgency": "urgency", "labels.expected_route": "expected_route",
        "labels.answerable_from_docs": "answerable", "labels.expected_doc_ids": "doc_ids",
        "labels.must_not_auto_respond": "must_escalate",
        "history.first_contact_resolution": "fcr", "history.resolution_time_minutes": "minutes",
        "history.csat_rating": "csat", "history.escalated": "escalated", "history.repeat_contact": "repeat",
    })


PII_PATTERNS = {
    "email address": r"[\w.+-]+@[\w-]+\.[\w.]+",
    "phone number": r"\+?\d[\d\s().-]{8,}\d",
    "key or token-like string": r"\b(?:sk|pk|api|key|tok)[-_][A-Za-z0-9]{8,}\b",
    "card-like number": r"\b(?:\d[ -]?){13,16}\b",
}


def build(df, docs):
    n = len(df)
    esc = df[df.escalated]
    ans = df[df.answerable]
    out = [f"# Discovery evidence\n\nGenerated by `python -m discovery.evidence` from {n} development tickets "
           f"and {len(docs)} documentation articles. Figures only; interpretation belongs in the workbook.\n"]

    # Section 1: interview claims set against the data
    tiers = df.groupby("customer_tier")["minutes"].median()
    urg = df.groupby("urgency")["minutes"].median()
    fl = df.groupby("language_fluency")[["csat", "fcr", "repeat"]].mean()
    top = df.intent.value_counts()
    tier1_resolvable = esc[esc.answerable & ~esc.must_escalate & (esc.expected_route == "auto_respond")]
    claims = pd.DataFrame([
        ["C1", "Marcus", "FCR is 42%", f"FCR {pct(df.fcr.mean())}"],
        ["C2", "Marcus", "Tickets are 'broadly' authentication, deployment, billing, API",
         "Top 5 intents: " + ", ".join(f"{k} {v}" for k, v in top.head(5).items())
         + f"; largest single intent is {pct(top.iloc[0] / n)} of volume"],
        ["C3", "Sofia", "About 7 in 10 tickets are questions already answered before",
         f"Answerable from docs: {pct(df.answerable.mean())}"],
        ["C4", "Daniel", "About half of escalations could have been resolved by tier one",
         f"{esc.answerable.sum()}/{len(esc)} escalated tickets ({pct(esc.answerable.mean())}) were answerable "
         f"from docs; {len(tier1_resolvable)} ({pct(len(tier1_resolvable) / len(esc))}) if also requiring "
         "expected_route auto_respond and not must_not_auto_respond"],
        ["C5", "Sofia", "Non-fluent customers have the worst satisfaction",
         " vs ".join(f"{k}: CSAT {r.csat:.2f}, FCR {pct(r.fcr)}, repeat {pct(r['repeat'])}" for k, r in fl.iterrows())],
        ["C6", "Ravi", "Urgent problems wait in the same queue as trivial ones",
         "Median resolution minutes by urgency: " + ", ".join(f"{k} {v:.0f}" for k, v in urg.items())],
        ["C7", "Ravi", "Enterprise customers get answers in about an hour",
         "Median resolution minutes by tier: " + ", ".join(f"{k} {v:.0f}" for k, v in tiers.items())],
        ["C8", "Ines / Sofia", "Docs are accurate but can't be found (Ines: search; Sofia: findability)",
         f"{pct(ans.escalated.mean())} of doc-answerable tickets were still escalated "
         f"({ans.escalated.sum()}/{len(ans)})"],
    ], columns=["ID", "Who", "Claim", "What the data shows"])
    out += ["## E1. Interview claims checked against the data (workbook §1)\n", table(claims), ""]

    # Section 2: counts
    out += ["## E2. Headline figures (workbook §2)\n", table(pd.DataFrame([
        ["Tickets", n], ["Unique customers", df.customer_id.nunique()],
        ["First contact resolution", pct(df.fcr.mean())], ["Escalated", pct(df.escalated.mean())],
        ["Mean CSAT (1-5)", round(df.csat.mean(), 2)], ["Repeat contacts", pct(df.repeat.mean())],
        ["Answerable from docs", pct(df.answerable.mean())],
        ["Must never auto-respond", pct(df.must_escalate.mean())],
        ["Expected route auto_respond", pct((df.expected_route == "auto_respond").mean())],
        ["Mean / median resolution minutes", f"{df.minutes.mean():.0f} / {df.minutes.median():.0f}"],
        ["Resolved within 120 min", pct((df.minutes <= 120).mean())],
    ], columns=["Measure", "Value"])), "",
        "Note: `resolution_time_minutes` is time to resolution, not time to first reply, "
        "so it is only a proxy for the 2-hour first-response SLA.\n"]
    for eid, col in [("E3", "channel"), ("E4", "urgency"), ("E5", "customer_tier"),
                     ("E6", "language_fluency"), ("E7", "customer_region"), ("E8", "intent")]:
        out += [f"## {eid}. Outcomes by {col} (workbook §2)\n", table(outcomes_by(df, col)), ""]

    cited = df.doc_ids.explode().dropna().value_counts()
    titles = {d["doc_id"]: d["title"] for d in docs}
    out += ["## E9. Most-needed articles: how many tickets a correct answer should cite each (workbook §2)\n",
            table(pd.DataFrame({"doc_id": cited.index, "title": [titles.get(i, "?") for i in cited.index],
                                "tickets": cited.values}).head(10)), ""]

    ae = df.groupby("answerable").agg(tickets=("fcr", "size"), escalated=("escalated", "mean"),
                                      csat=("csat", "mean"), repeat=("repeat", "mean"))
    ae[["escalated", "repeat"]] = ae[["escalated", "repeat"]].apply(lambda s: s.map(pct))
    ae["csat"] = ae.csat.round(2)
    out += ["## E10. Answerable from docs vs not (workbook §2)\n", table(ae), ""]
    g = ans.groupby("escalated").agg(tickets=("fcr", "size"), csat=("csat", "mean"),
                                     median_minutes=("minutes", "median"), repeat=("repeat", "mean"))
    g["csat"], g["repeat"] = g.csat.round(2), g.repeat.map(pct)
    out += ["## E11. Doc-answerable tickets only: escalated vs not (workbook §2)\n", table(g), ""]
    ch = ans.groupby("channel")["escalated"].agg(["size", "mean"]).rename(
        columns={"size": "answerable tickets", "mean": "still escalated"})
    ch["still escalated"] = ch["still escalated"].map(pct)
    out += ["## E12. Doc-answerable tickets still escalated, by channel (workbook §2)\n", table(ch), ""]

    # Section 3: effort. Elapsed resolution minutes stand in for agent effort; no handling-time field exists.
    eff = df.groupby("intent").agg(tickets=("fcr", "size"), minutes=("minutes", "sum"),
                                   escalated=("escalated", "mean"), answerable=("answerable", "mean"),
                                   must_escalate=("must_escalate", "mean"))
    eff["volume share"] = (eff.tickets / n).map(pct)
    eff["minutes share"] = (eff.minutes / eff.minutes.sum()).map(pct)
    eff = eff.sort_values("minutes", ascending=False)
    for c in ["escalated", "answerable", "must_escalate"]:
        eff[c] = eff[c].map(pct)
    out += ["## E13. Volume share vs share of resolution minutes, by intent (workbook §3)\n",
            "Proxy: summed `resolution_time_minutes` (elapsed, not hands-on time).\n",
            table(eff[["tickets", "volume share", "minutes share", "escalated", "answerable", "must_escalate"]]), ""]

    # Section 5: data quality and private data
    text = df.subject.fillna("") + " " + df.body.fillna("")
    pii = pd.DataFrame([[k, int(text.str.contains(p, regex=True).sum())] for k, p in PII_PATTERNS.items()],
                       columns=["Pattern (regex, approximate)", "Tickets matching"])
    out += ["## E14. Private data in ticket text (workbook §5)\n", table(pii), "",
            "Customer names and IDs are in structured fields (`customer_name`, `customer_id`), "
            "not the free text; any reply that echoes them carries private data.\n"]
    no_doc = df[~df.answerable].intent.value_counts()
    review = pd.Series([d.get("last_reviewed_days_ago") for d in docs])
    by_cat = pd.Series([d["category"] for d in docs]).value_counts()
    out += ["## E15. Documentation coverage (workbook §5)\n",
            f"- Articles: {len(docs)} across {by_cat.size} categories: "
            + ", ".join(f"{k} {v}" for k, v in by_cat.items()),
            f"- `last_reviewed_days_ago`: min {review.min()}, max {review.max()} "
            "(a constant value cannot show staleness)",
            f"- Articles never needed by any dev ticket: {sorted(set(titles) - set(cited.index)) or 'none'}",
            "- Intents with tickets not answerable from docs: "
            + ", ".join(f"{k} {v}/{(df.intent == k).sum()}" for k, v in no_doc.items()), ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tickets", default=ROOT / "data/development_tickets.json")
    ap.add_argument("--docs", default=ROOT / "data/documentation.json")
    ap.add_argument("--output", default=ROOT / "discovery/evidence.md")
    a = ap.parse_args()
    md = build(load(a.tickets), json.loads(Path(a.docs).read_text()))
    Path(a.output).write_text(md)
    print(f"wrote {a.output}")


if __name__ == "__main__":
    main()
